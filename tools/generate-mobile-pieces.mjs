// Inlines assets/pieces/*.svg into a TypeScript module for react-native-svg,
// because Metro cannot import .svg files without an extra transformer.
// Usage: node tools/generate-mobile-pieces.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const piecesDir = fileURLToPath(new URL('../assets/pieces/', import.meta.url));
const target = fileURLToPath(
  new URL('../apps/mobile/src/features/board/pieceXml.ts', import.meta.url),
);

const entries = readdirSync(piecesDir)
  .filter((name) => name.endsWith('.svg'))
  .sort()
  .map((name) => {
    const xml = readFileSync(piecesDir + name, 'utf8')
      .replace(/<\?xml[^>]*\?>\s*/, '')
      .replace(/>\s+</g, '><')
      .trim();
    return `  ${name.slice(0, -4)}: ${JSON.stringify(xml)},`;
  });

writeFileSync(
  target,
  `// Generated by tools/generate-mobile-pieces.mjs from assets/pieces. Do not edit by hand.\nexport const PIECE_XML: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`Wrote ${target}`);
