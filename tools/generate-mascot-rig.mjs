// Converts the design package's cat-rig.svg into the typed data in packages/mascot/src/rig.ts.
// Usage: node tools/generate-mascot-rig.mjs <path to cat-rig.svg>
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error('Usage: node tools/generate-mascot-rig.mjs <path to cat-rig.svg>');
  process.exit(1);
}

const RIM_VALUE = 'var(--cat-rim, #1E1A2F)';
const RIM_TOKEN = '$rim';

const svg = readFileSync(source, 'utf8');
const body = svg.slice(svg.indexOf('<ellipse'), svg.lastIndexOf('</svg>'));

// camelCase for React and react-native-svg, data-* attributes stay as they are
function propName(name) {
  return name.startsWith('data-') ? name : name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
}

function parseAttrs(source) {
  const attrs = {};
  for (const [, name, value] of source.matchAll(/([\w:-]+)="([^"]*)"/g)) {
    attrs[propName(name)] = value === RIM_VALUE ? RIM_TOKEN : value;
  }
  return attrs;
}

const root = { children: [] };
const stack = [root];
for (const [, closing, tag, rest, selfClosing] of body.matchAll(
  /<(\/?)([a-zA-Z]+)([^>]*?)(\/?)>/g,
)) {
  if (closing) {
    stack.pop();
    continue;
  }
  const node = { tag, attrs: parseAttrs(rest), children: [] };
  stack.at(-1).children.push(node);
  if (!selfClosing) stack.push(node);
}

// Parts that moods tweak (jump, pupils, chest) have no data-layer in the source, so name them here
let translateGroups = 0;
function markLayers(node) {
  const { attrs } = node;
  if (node.tag === 'g' && attrs.transform === 'translate(0,0)' && !attrs['data-layer']) {
    attrs['data-layer'] = translateGroups === 0 ? 'jump' : 'pupils';
    translateGroups += 1;
  }
  if (node.tag === 'ellipse' && attrs.cy === '160' && attrs.rx === '22')
    attrs['data-layer'] = 'chest';
  node.children.forEach(markLayers);
}
root.children.forEach(markLayers);

function strip(node) {
  const out = { tag: node.tag, attrs: node.attrs };
  if (node.children.length > 0) out.children = node.children.map(strip);
  return out;
}

const output = `// Generated by tools/generate-mascot-rig.mjs from the design package (shared/assets/cat/cat-rig.svg).
// Do not edit by hand.
import type { RigNode } from './types.js';

export const RIM = '${RIM_TOKEN}';

export const RIG: RigNode[] = ${JSON.stringify(root.children.map(strip), null, 2)};
`;

const target = fileURLToPath(new URL('../packages/mascot/src/rig.ts', import.meta.url));
writeFileSync(target, output);
console.log(`Wrote ${target}`);
