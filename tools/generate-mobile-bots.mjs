// Inlines assets/bots/*.svg into a TypeScript module for react-native-svg,
// because Metro cannot import .svg files without an extra transformer.
// Usage: node tools/generate-mobile-bots.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const botsDir = fileURLToPath(new URL('../assets/bots/', import.meta.url));
const target = fileURLToPath(
  new URL('../apps/mobile/src/features/play/botXml.ts', import.meta.url),
);

const entries = readdirSync(botsDir)
  .filter((name) => name.endsWith('.svg'))
  .sort()
  .map((name) => {
    const xml = readFileSync(botsDir + name, 'utf8')
      .replace(/<\?xml[^>]*\?>\s*/, '')
      .replace(/>\s+</g, '><')
      .trim();
    return `  ${JSON.stringify(name.slice(0, -4))}: ${JSON.stringify(xml)},`;
  });

writeFileSync(
  target,
  `// Generated by tools/generate-mobile-bots.mjs from assets/bots. Do not edit by hand.\nexport const BOT_XML: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`Wrote ${target}`);
