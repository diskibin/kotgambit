// Inlines assets/pieces/*.svg (the cat's own set) and assets/piece-sets/<set>/*.svg (the other sets) into a
// TypeScript module for react-native-svg, because Metro cannot import .svg files without an extra transformer.
// Usage: node tools/generate-mobile-pieces.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const piecesDir = fileURLToPath(new URL('../assets/pieces/', import.meta.url));
const setsDir = fileURLToPath(new URL('../assets/piece-sets/', import.meta.url));
const target = fileURLToPath(
  new URL('../apps/mobile/src/features/board/pieceXml.ts', import.meta.url),
);

/** The lines `wK: "<svg ...>",` of one folder of twelve files. */
function readSet(dir) {
  return readdirSync(dir)
    .filter((name) => name.endsWith('.svg'))
    .sort()
    .map((name) => {
      const xml = readFileSync(dir + name, 'utf8')
        .replace(/<\?xml[^>]*\?>\s*/, '')
        .replace(/>\s+</g, '><')
        .trim();
      return `    ${name.slice(0, -4)}: ${JSON.stringify(xml)},`;
    });
}

const sets = readdirSync(setsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const block = (name, lines) => `  ${name}: {\n${lines.join('\n')}\n  },`;

const body = [
  '// Generated by tools/generate-mobile-pieces.mjs from assets/pieces and assets/piece-sets. Do not edit by hand.',
  'export const PIECE_SET_XML: Record<string, Record<string, string>> = {',
  block('gambit', readSet(piecesDir)),
  ...sets.map((set) => block(JSON.stringify(set), readSet(`${setsDir}${set}/`))),
  '};',
  '',
].join('\n');

writeFileSync(target, body);
console.log(`Wrote ${target} with the sets gambit, ${sets.join(', ')}`);
